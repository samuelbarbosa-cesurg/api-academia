DROP TABLE IF EXISTS pagamentos CASCADE;
DROP TABLE IF EXISTS inscricoes CASCADE;
DROP TABLE IF EXISTS turmas CASCADE;
DROP TABLE IF EXISTS modalidades CASCADE;
DROP TABLE IF EXISTS instrutores CASCADE;
DROP TABLE IF EXISTS alunos CASCADE;
DROP TABLE IF EXISTS planos CASCADE;

CREATE TABLE planos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(60) NOT NULL UNIQUE,
  valor_mensal NUMERIC(10,2) NOT NULL CHECK (valor_mensal > 0),
  duracao_meses INTEGER NOT NULL CHECK (duracao_meses > 0)
);

CREATE TABLE alunos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  cpf CHAR(11) NOT NULL UNIQUE,
  email VARCHAR(120) NOT NULL UNIQUE,
  data_nascimento DATE NOT NULL,
  plano_id INTEGER NOT NULL REFERENCES planos(id),
  inicio_plano DATE NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  -- restrição própria 1: e-mail sempre em minúsculas
  CONSTRAINT alunos_email_minusculo CHECK (email = lower(email))
);

CREATE TABLE instrutores (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  cref VARCHAR(20) NOT NULL UNIQUE,
  email VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE modalidades (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE turmas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  modalidade_id INTEGER NOT NULL REFERENCES modalidades(id),
  instrutor_id INTEGER NOT NULL REFERENCES instrutores(id),
  dia_semana VARCHAR(10) NOT NULL
    CHECK (dia_semana IN ('segunda', 'terca', 'quarta', 'quinta', 'sexta', 'sabado')),
  horario TIME NOT NULL,
  vagas INTEGER NOT NULL CHECK (vagas > 0 AND vagas <= 40),
  -- restrição própria 2: o instrutor não dá duas turmas no mesmo dia e horário
  CONSTRAINT turmas_instrutor_horario_unico UNIQUE (instrutor_id, dia_semana, horario)
);

-- N:N entre alunos e turmas
CREATE TABLE inscricoes (
  aluno_id INTEGER NOT NULL REFERENCES alunos(id),
  turma_id INTEGER NOT NULL REFERENCES turmas(id),
  inscrito_em DATE NOT NULL DEFAULT CURRENT_DATE,
  PRIMARY KEY (aluno_id, turma_id)
);

CREATE TABLE pagamentos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aluno_id INTEGER NOT NULL REFERENCES alunos(id),
  mes_referencia DATE NOT NULL CHECK (EXTRACT(DAY FROM mes_referencia) = 1),
  valor NUMERIC(10,2) NOT NULL CHECK (valor > 0),
  status VARCHAR(10) NOT NULL CHECK (status IN ('pendente', 'pago', 'atrasado')),
  pago_em DATE,
  UNIQUE (aluno_id, mes_referencia),
  CHECK ((status = 'pago') = (pago_em IS NOT NULL))
);

